"""Render docs/hl7-field-notes.md from the builders' FIELDS_USED table and the
standard's field metadata in hl7_spec, with one sample of each message form.

The notes double as study notes for the HL7 v2 control specialist exam: for
every segment and field the flow uses, the data type and optionality come from
the v2.8 (or v2.5.1) tables, and the "why it matters" column is the billing or
audit reason the field is carried.
"""
from __future__ import annotations

from datetime import date, datetime

from flow import hl7_messages as hm
from flow import hl7_spec
from flow.registration import Coverage, Patient
from flow.vocab import load as load_vocab

# One fictitious resident, two coverage rows, one knee order and its report.
PATIENT = Patient("MRN1000001", "synthetic-1", "ASHFORD", "AVERY", date(1942, 3, 5), "F", "F01", date(2024, 1, 15))
COVERAGE = [
    Coverage("COV0000001", "MRN1000001", "MAA", "MAA12345676", 1, date(2024, 11, 1), date(2025, 10, 31)),
    Coverage("COV0000002", "MRN1000001", "CPA", "CPA123456781", 2, date(2024, 11, 1), date(2025, 10, 31)),
]
ORDER = hm.OrderFacts(
    placer_order_number="PLC0000001", filler_order_number="FIL0000001", accession="ACC00000001",
    study_instance_uid="1.2.826.0.1.3680043.8.498.10000000000000000000000000000001",
    order_datetime=datetime(2025, 3, 4, 8, 15), scheduled_datetime=datetime(2025, 3, 4, 10, 0),
    cpt="73562", description="Radiologic examination knee 3 views", laterality="L",
    ordering_npi="1234567893", ordering_family="BARLOW", ordering_given="BLAKE",
    reason="Fall from bed with knee pain and swelling",
)
REPORT = hm.ReportFacts(
    exam_datetime=datetime(2025, 3, 4, 10, 12), report_datetime=datetime(2025, 3, 4, 14, 40),
    radiologist_npi=load_vocab().facilities[1].npi, radiologist_family="CALDWELL", radiologist_given="CAMERON", text="SYNTHETIC - NOT A READ",
)
NOW = datetime(2025, 3, 4, 8, 16)

SEGMENT_INTRO = {
    "MSH": "Message header. Every message starts here: who sent it, when, what kind, and which version's field tables apply.",
    "EVN": "Event type. Carries the time the registration event was recorded; in v2.8 the event code itself lives only in MSH-9.",
    "PID": "Patient identification. The MRN here is the key every later hop must repeat exactly.",
    "PV1": "Patient visit. The patient class and the location: a nursing-facility resident seen as an outpatient at a named facility.",
    "IN1": "Insurance. One per coverage row: the payer, the dates it is in force, the priority, and the member ID the claim must carry.",
    "ORC": "Common order. The order control code and the two order numbers that the report quotes back.",
    "TQ1": "Timing/quantity (v2.7+). The scheduled start of the exam; it replaced ORC-7.",
    "OBR": "Observation request. The service ordered, and on the report the exam and report times and the result status.",
    "PRT": "Participation (v2.7+). Who took part and in what role; it replaced the XCN provider fields on ORC and OBR.",
    "IPC": "Imaging procedure control (imaging orders). The accession, requested procedure, Study Instance UID and modality the modality worklist needs.",
    "OBX": "Observation/result. The report body, one text observation here.",
}


def samples() -> dict[str, tuple[str, str]]:
    """(version, ER7) per sample name, in document order."""
    v = load_vocab()
    return {
        "ADT^A04 (v2.8, structure ADT_A01)": ("2.8", hm.adt_a04(PATIENT, COVERAGE, v, version="2.8", control_id="ADT0000001", now=NOW)),
        "ADT^A04 (v2.5.1)": ("2.5.1", hm.adt_a04(PATIENT, COVERAGE, v, version="2.5.1", control_id="ADT0000001", now=NOW)),
        "OMI^O23 imaging order (v2.8)": ("2.8", hm.order_v28(PATIENT, ORDER, v, control_id="ORD0000001", now=NOW)),
        "ORM^O01 order (v2.5.1, the form most RIS/PACS interfaces still send)": ("2.5.1", hm.order_v251(PATIENT, ORDER, v, control_id="ORD0000001", now=NOW)),
        "ORU^R01 report (v2.8)": ("2.8", hm.report_v28(PATIENT, ORDER, REPORT, v, control_id="RPT0000001", now=REPORT.report_datetime)),
        "ORU^R01 report (v2.5.1)": ("2.5.1", hm.report_v251(PATIENT, ORDER, REPORT, v, control_id="RPT0000001", now=REPORT.report_datetime)),
    }


def _cardinality(info: hl7_spec.FieldInfo) -> str:
    req = "required" if info.required else "optional"
    rep = ", repeats" if info.repeats else ""
    return req + rep


def render() -> str:
    lines: list[str] = []
    lines += [
        "# HL7 v2 field notes",
        "",
        "Generated by `scripts/write_field_notes.py` from the message builders' field table and the standard's field metadata (via hl7apy's tables); `tests/test_field_notes.py` fails when this file is stale.",
        "",
        "Two forms of every message are written, and which is which:",
        "",
        "- **v2.8** is the current standard: ADT^A04 uses the ADT_A01 structure; the imaging order is OMI^O23 with an IPC segment (ORM^O01 was withdrawn in v2.7); participants go in PRT segments; EVN-1 and ORC-7 are withdrawn and left empty in position.",
        "- **v2.5.1** is what most RIS, PACS and modality worklist interfaces still send (IHE Scheduled Workflow is written against v2.3.1/v2.5.1): ORM^O01 with the accession in OBR-18, the ordering provider in ORC-12 and OBR-16, and the reader in OBR-32.",
        "",
        "Data types to know: ST string, ID coded value from an HL7 table, IS coded value from a user table, CWE coded with exceptions (v2.8's successor to CE), CX extended composite ID (an identifier with its assigning authority and type), XPN person name, XCN extended composite ID and name (a provider with an identifier), XON organization name, EI entity identifier, DT date, DTM date/time (v2.8; TS in v2.5.1), NDL name with date and location.",
        "",
        "Fields are numbered as the standard numbers them. A field hl7apy drops from its table because v2.8 withdrew it (EVN-1, ORC-7, OBR-14/15/27) still occupies its position, which is why the encoder in `src/flow/er7.py` places fields by number.",
        "",
        "## Segments and fields the flow uses",
        "",
    ]
    by_segment: dict[str, list[tuple[int, str, hm.FieldUse]]] = {}
    for (version, segment, number), use in hm.FIELDS_USED.items():
        by_segment.setdefault(segment, []).append((number, version, use))
    order = ["MSH", "EVN", "PID", "PV1", "IN1", "ORC", "TQ1", "OBR", "PRT", "IPC", "OBX"]
    for segment in order:
        rows = sorted(by_segment.get(segment, []), key=lambda r: (r[0], r[1]))
        if not rows:
            continue
        lines += [f"### {segment}", "", SEGMENT_INTRO.get(segment, ""), "", "| field | name | data type | optionality | versions | in | why it matters |", "|---|---|---|---|---|---|---|"]
        seen: set[int] = set()
        for number, version, use in rows:
            if number in seen:
                continue
            seen.add(number)
            versions = [v for (v, s, n) in hm.FIELDS_USED if s == segment and n == number]
            infos = {v: hl7_spec.field_info(v, segment, number) for v in versions}
            primary = infos.get("2.8") or infos[versions[0]]
            dtypes = sorted({i.datatype for i in infos.values()})
            dtype = " / ".join(f"{i.datatype} (v{v})" for v, i in sorted(infos.items(), reverse=True)) if len(dtypes) > 1 else dtypes[0]
            cards = {v: _cardinality(i) for v, i in infos.items()}
            card = cards[primary.version] if len(set(cards.values())) == 1 else "; ".join(f"{c} (v{v})" for v, c in sorted(cards.items(), reverse=True))
            name = primary.long_name.replace("_", " ").lower()
            lines.append(f"| {segment}-{number} | {name} | {dtype} | {card} | {', '.join('v' + v for v in sorted(versions, reverse=True))} | {', '.join(use.messages)} | {use.purpose} |")
        lines.append("")
    lines += ["## Sample messages", "", "Synthetic throughout: a fictitious resident, a fictitious facility, synthetic NPIs, generic payers. Segment terminators are carriage returns in the files; they are shown as line breaks here.", ""]
    for name, (version, er7) in samples().items():
        lines += [f"### {name}", "", "```", er7.replace("\r", "\n").rstrip("\n"), "```", ""]
    lines += [
        "## Reading a message, field by field",
        "",
        "A field is found by counting pipes from the segment name: `PID|1||MRN...` puts `1` in PID-1, nothing in PID-2 and the MRN in PID-3. Components inside a field are separated by `^`, repeats by `~`, sub-components by `&`, and `\\` escapes a delimiter inside a value. MSH is the one exception: MSH-1 is the field separator itself and MSH-2 the four encoding characters.",
        "",
        "The review joins the hops on three keys: the MRN (PID-3) from registration to everything, the accession (IPC-1 in v2.8, OBR-18 in v2.5.1) from order to image to claim, and the placer order number (ORC-2) from order to report. The errors the review catches are the places those keys and the fields around them disagree (`docs/error-catalog.md`): E01 and E04 on the accession, E08 on the ordering NPI (PRT-5 or ORC-12/OBR-16 against the claim), E05 to E07 on IN1-36, IN1-12/13 and IN1-2 against the claim's payer and member ID, E09 on OBR-7 against OBR-22, and the order's statement of condition in OBR-31, which 42 CFR 486.106(a)(2) requires on a portable x-ray order.",
        "",
    ]
    return "\n".join(lines)
